            Ingress("v1-self-origin", "Our own heartbeat, heard back off the broadcast. Passes steps 1 and 2 by construction",
                selfOrigin, rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "SelfOrigin"),

            Ingress("v1-not-in-roster", "Valid mac from a machine outside a complete roster",
                stranger, rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "NotInRoster"),

            Ingress("v1-pairing-enrollment", "The same datagram with an incomplete roster and the pairing window open",
                stranger, rosterPeer: null, localSeq: 0, pairingWindowOpen: true, "PairingEnrollment"),

            Ingress("v1-pairing-window-closed", "Incomplete roster but the window has expired; both conditions are required",
                stranger, rosterPeer: null, localSeq: 0, pairingWindowOpen: false, "NotInRoster"),

            Ingress("v1-seq-at-bound", "Delta of exactly 1000 is accepted",
                SignedWithSeq(1041), rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "Accepted"),

            Ingress("v1-seq-over-bound", "Delta of 1001 is dropped and raises error",
                SignedWithSeq(1042), rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "SeqOutOfBounds"),

            Ingress("v1-seq-max-over-bound", "seq = uint64.Max, which unbounded would pin ownership forever on both machines",
