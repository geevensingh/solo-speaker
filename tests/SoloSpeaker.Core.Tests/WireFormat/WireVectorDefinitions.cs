using System.Text;
using SoloSpeaker.Core.PeerLink.Wire;

namespace SoloSpeaker.Core.Tests.WireFormat;

/// <summary>
/// The source definitions the frozen artifact is generated from.
/// </summary>
/// <remarks>
/// <para>
/// This describes <em>which</em> vectors exist and what field values they carry.
/// <c>docs/wire-format.vectors.json</c> holds what the codec produces for them - the
/// canonical bytes and the MACs - and is the thing that freezes. The test compares the two
/// on every run, so the pair cannot drift.
/// </para>
/// <para>
/// Honest bound on what this proves: the artifact was generated by the canonicalizer it
/// freezes, so it cannot catch an error that was present when it was written. What it
/// catches is <em>change</em>.
/// </para>
/// </remarks>
public static class WireVectorDefinitions
{
    private const string ForeignPairIdHex = "00112233445566778899aabbccddeeff";

    private static readonly byte[] ForeignPairKey = [.. Enumerable.Repeat((byte)0xff, 32)];

    /// <summary>Regenerates the whole artifact from the current codec.</summary>
    public static WireVectorFile Build()
    {
        List<RoundTripVector> roundTrip =
        [
            RoundTrip("v1-baseline", "Nominal datagram, micLive false, bye false, mid-range seq",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.MachineBHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-miclive-true", "Phase 2 shape, proving phase 1 and 2 are wire-compatible",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.MachineBHex, micLive: true, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-bye", "The departure datagram",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.MachineBHex, micLive: false, bye: true, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-bye-higher-seq", "bye with seq strictly above the receiver's; activeOwner must not move",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 9999,
                    WireVectorConstants.MachineBHex, micLive: false, bye: true, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-seq-zero", "seq 0, guarding leading-zero and empty-integer formatting",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 0,
                    WireVectorConstants.NoneHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-seq-max", "seq at uint64.Max, guarding 64-bit parse precision",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, ulong.MaxValue,
                    WireVectorConstants.MachineBHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-owner-is-peer", "activeOwner naming the other roster entry",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.MachineAHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-owner-unknown", "activeOwner outside the roster; a reducer outcome, not an ingress rejection",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.StrangerHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-owner-none", "activeOwner is MachineId.None, the pre-claim state of design.md section 5",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 7,
                    WireVectorConstants.NoneHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)),

            RoundTrip("v1-date-padding", "Single-digit month and day, freezing rule 8 zero-padding",
                WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                    WireVectorConstants.MachineBHex, micLive: false, bye: false, "2026-01-05T03:04:05.006Z")),
        ];

        string baseline = roundTrip[0].Datagram;
        string byeDatagram = roundTrip[2].Datagram;

        string foreign = WireVectorConstants.Build(
            WireVectorConstants.Datagram(1, ForeignPairIdHex, WireVectorConstants.MachineBHex, 41,
                WireVectorConstants.MachineBHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc),
            ForeignPairKey).Datagram;

        string selfOrigin = WireVectorConstants.Build(
            WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineAHex, 41,
                WireVectorConstants.MachineAHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)).Datagram;

        string stranger = WireVectorConstants.Build(
            WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.StrangerHex, 1,
                WireVectorConstants.NoneHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)).Datagram;

        string unknownVersion = WireVectorConstants.Build(
            WireVectorConstants.Datagram(2, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, 41,
                WireVectorConstants.MachineBHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)).Datagram;

        static string SignedWithSeq(ulong seq) => WireVectorConstants.Build(
            WireVectorConstants.Datagram(1, WireVectorConstants.PairIdHex, WireVectorConstants.MachineBHex, seq,
                WireVectorConstants.MachineBHex, micLive: false, bye: false, WireVectorConstants.BaselineSentUtc)).Datagram;

        List<IngressVector> ingress =
        [
            Ingress("v1-foreign-pairid", "Another pairing's datagram, signed with another key. Fails steps 1 and 2; must report step 1",
                foreign, rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "ForeignPairId"),

            Ingress("v1-bad-mac", "One flipped bit in mac",
                FlipLastMacCharacter(baseline), rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-missing-miclive", "Field absent: a version mismatch, never inferred as false. Unverifiable, so step 2",
                baseline.Replace(",\"micLive\":false", string.Empty, StringComparison.Ordinal),
                rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-missing-bye", "Field absent: a version mismatch, never inferred as false",
                baseline.Replace(",\"bye\":false", string.Empty, StringComparison.Ordinal),
                rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-unknown-key", "An extra field, the shape a v2 peer takes. Must pass step 1 and die at step 2 so it is counted",
                InsertBeforeClose(baseline, ",\"extra\":1"),
                rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-duplicate-key", "A repeated field; JSON permits it, canonicalization does not",
                InsertBeforeClose(baseline, ",\"seq\":41"),
                rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-trailing-bytes", "Rule 4 forbids insignificant whitespace, so a canonical document is consumed exactly",
