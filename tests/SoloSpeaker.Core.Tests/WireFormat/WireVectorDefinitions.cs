            Ingress("v1-seq-below-local", "A lower seq, which section 5.4 ignores silently. Guards the unsigned-subtraction wrap",
                SignedWithSeq(5), rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "Accepted"),

            Ingress("v1-seq-wrap-guard", "localSeq at uint64.Max against seq 0; must not be read as a delta of 1",
                SignedWithSeq(0), rosterPeer: "B", localSeq: ulong.MaxValue, pairingWindowOpen: false, "Accepted"),

            Ingress("v1-unknown-version", "v 2 with every field present and a valid mac - the only shape that reaches step 5",
                unknownVersion, rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "UnknownVersion"),

            Ingress("v1-bye-bad-mac", "A bye is exempt from section 5.4, never from ingress",
                FlipLastMacCharacter(byeDatagram), rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "BadMac"),

            Ingress("v1-oversize", "Over the 512-byte bound, rejected before step 1",
                baseline.PadRight(WireProtocol.MaxDatagramBytes + 1),
                rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "Unreadable"),

            Ingress("v1-not-json", "Not a JSON object; attributable to no numbered step",
                "not a datagram", rosterPeer: "B", localSeq: 41, pairingWindowOpen: false, "Unreadable"),
        ];

        return new WireVectorFile
        {
            Comment =
                "Normative golden vectors for wire format v1. See docs/wire-format.md. " +
                "The pairKey below is a published test constant that authenticates nothing; " +
                "it is not the secret AGENTS.md section 6 protects. Regenerate with " +
                "SOLO_SPEAKER_UPDATE_WIRE_VECTORS=1 and review the diff - a change here is a " +
                "change to a format design.md section 8 freezes in phase 1.",
            TestPairKeyHex = Convert.ToHexStringLower(WireVectorConstants.TestPairKey),
            PairIdHex = WireVectorConstants.PairIdHex,
            MachineAHex = WireVectorConstants.MachineAHex,
            MachineBHex = WireVectorConstants.MachineBHex,
            StrangerHex = WireVectorConstants.StrangerHex,
            RoundTrip = roundTrip,
            Ingress = ingress,
        };
    }

    private static RoundTripVector RoundTrip(string name, string covers, PeerDatagram datagram)
    {
        (string canonical, string full, string mac) = WireVectorConstants.Build(datagram);

        return new RoundTripVector
        {
            Name = name,
            Covers = covers,
            Version = datagram.Version,
            PairId = datagram.PairId.ToString(),
            MachineId = datagram.SenderId.ToString(),
            Seq = datagram.Seq,
            ActiveOwner = datagram.ActiveOwner.ToString(),
            MicLive = datagram.MicLive,
            Bye = datagram.Bye,
            SentUtc = Encoding.UTF8.GetString(TimestampOf(canonical)),
            Canonical = canonical,
            Datagram = full,
            Mac = mac,
        };
    }

    private static IngressVector Ingress(
        string name, string covers, string datagram,
        string? rosterPeer, ulong localSeq, bool pairingWindowOpen, string expected) =>
        new()
        {
            Name = name,
            Covers = covers,
            Datagram = datagram,
            RosterPeer = rosterPeer,
            LocalSeq = localSeq,
            PairingWindowOpen = pairingWindowOpen,
            Expected = expected,
        };

    /// <summary>Extracts the <c>sentUtc</c> value straight out of the canonical text.</summary>
    private static byte[] TimestampOf(string canonical)
    {
        const string marker = "\"sentUtc\":\"";
        int start = canonical.IndexOf(marker, StringComparison.Ordinal) + marker.Length;
        return Encoding.UTF8.GetBytes(canonical.Substring(start, 24));
    }

    private static string FlipLastMacCharacter(string datagram)
    {
        char[] characters = datagram.ToCharArray();
        int position = characters.Length - 3;
        characters[position] = characters[position] == '0' ? '1' : '0';
        return new string(characters);
    }

    private static string InsertBeforeClose(string datagram, string addition) =>
        string.Concat(datagram.AsSpan(0, datagram.Length - 1), addition, "}");
}
